/** Billing-frequency label (Monthly / Quarterly / Display Drive), translated. */
function freqLabel(string $f): string
{
    return [
        'monthly'       => t('monthly'),
        'quarterly'     => t('quarterly'),
        'display_drive' => t('display_drive'),
    ][$f] ?? ucfirst(str_replace('_', ' ', $f));
}

/** URL of the current page with the language switched; other GET params kept. */
function langUrl(string $lang): string
{
    $params = $_GET;
    $params['lang'] = $lang;
    $page = basename($_SERVER['PHP_SELF'] ?? 'index.php');
    return $page . '?' . http_build_query($params);
}
